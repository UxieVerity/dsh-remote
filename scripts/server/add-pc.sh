#!/usr/bin/env bash
# Register one more PC and generate its nginx server blocks.
# Run as root from the skill repo. There is no fixed PC count.
#
# Required env:
#   BASE_DOMAIN
# Usage:
#   sudo -E BASE_DOMAIN=example.com bash scripts/server/add-pc.sh --name pc-c
#   ... --name office --label "办公室" --desc "备用机" --port 13082
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TEMPLATE="$ROOT/templates/nginx-pc.conf.template"
STATE_DIR="/etc/dsh-relay"
REGISTRY="$STATE_DIR/pcs.tsv"
PCS_DIR="/etc/nginx/dsh-pcs"
PCS_JSON="/srv/dsh-portal/pcs.json"
PORT_START="${PORT_BASE:-13080}"
PORT_END=65535

NAME=""
LABEL=""
DESC=""
PORT=""
BASE_DOMAIN="${BASE_DOMAIN:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)  NAME="${2:-}"; shift 2 ;;
    --label) LABEL="${2:-}"; shift 2 ;;
    --desc)  DESC="${2:-}"; shift 2 ;;
    --port)  PORT="${2:-}"; shift 2 ;;
    -h|--help)
      echo "usage: BASE_DOMAIN=example.com $0 --name pc-c [--label text] [--desc text] [--port 13082]"
      exit 0
      ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [[ "$(id -u)" -ne 0 ]]; then
  echo "run as root" >&2
  exit 1
fi
if [[ -z "$BASE_DOMAIN" ]]; then
  echo "BASE_DOMAIN is required" >&2
  exit 1
fi
if [[ ! "$PORT_START" =~ ^[0-9]+$ ]] || (( PORT_START < 1 || PORT_START > PORT_END )); then
  echo "PORT_BASE must be between 1 and $PORT_END" >&2
  exit 1
fi
if [[ -z "$NAME" ]]; then
  echo "--name is required" >&2
  exit 1
fi
if [[ ! "$NAME" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]]; then
  echo "name must be a lowercase DNS label (1-63 chars, letters/digits/hyphen, no leading/trailing hyphen)" >&2
  exit 1
fi
case "$NAME" in
  dsh|www|frp|localhost|mail|ns1|ns2|api)
    echo "name '$NAME' is reserved; choose another label" >&2
    exit 1
    ;;
esac
if [[ ! -f "$TEMPLATE" ]]; then
  echo "missing $TEMPLATE" >&2
  exit 1
fi
if ! command -v nginx >/dev/null; then
  echo "nginx is required" >&2
  exit 1
fi
if ! grep -q 'dsh-pcs' /etc/nginx/sites-enabled/dsh-relay.conf 2>/dev/null; then
  echo "the nginx site does not include /etc/nginx/dsh-pcs; run install-nginx-site.sh first" >&2
  exit 1
fi
if ! command -v python3 >/dev/null; then
  echo "python3 is required" >&2
  exit 1
fi

install -d -m 0755 "$STATE_DIR" "$PCS_DIR" /srv/dsh-portal
touch "$REGISTRY"
chmod 0644 "$REGISTRY"
if [[ ! -f "$PCS_JSON" ]]; then
  printf '[]\n' > "$PCS_JSON"
  chown root:www-data "$PCS_JSON"
  chmod 0644 "$PCS_JSON"
fi
if [[ ! -f "$PCS_DIR/00-empty.conf" ]]; then
  printf '# Per-PC server blocks are generated by scripts/server/add-pc.sh.\n' \
    > "$PCS_DIR/00-empty.conf"
fi

if awk -F '\t' -v n="$NAME" '$1==n{found=1} END{exit !found}' "$REGISTRY"; then
  echo "PC '$NAME' is already registered; remove it first or use another name" >&2
  exit 1
fi

port_in_use() {
  local p="$1"
  awk -F '\t' -v p="$p" '$2==p{found=1} END{exit !found}' "$REGISTRY" && return 0
  ss -lntH 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${p}$" && return 0
  return 1
}

if [[ -n "$PORT" ]]; then
  if [[ ! "$PORT" =~ ^[0-9]+$ ]] || (( PORT < PORT_START || PORT > PORT_END )); then
    echo "port must be between $PORT_START and $PORT_END" >&2
    exit 1
  fi
  if port_in_use "$PORT"; then
    echo "port $PORT is already allocated or listening" >&2
    exit 1
  fi
else
  PORT=""
  for p in $(seq "$PORT_START" "$PORT_END"); do
    if ! port_in_use "$p"; then
      PORT="$p"
      break
    fi
  done
  if [[ -z "$PORT" ]]; then
    echo "no free port in $PORT_START-$PORT_END" >&2
    exit 1
  fi
fi

if [[ -z "$LABEL" ]]; then
  LABEL="$NAME"
fi

CONF="$PCS_DIR/${NAME}.conf"
TMP_CONF="$(mktemp)"
REG_BACKUP="$(mktemp)"
JSON_BACKUP="$(mktemp)"
cp -a "$REGISTRY" "$REG_BACKUP"
cp -a "$PCS_JSON" "$JSON_BACKUP"

cleanup_failed() {
  rm -f "$TMP_CONF" "$CONF"
  cp -a "$REG_BACKUP" "$REGISTRY"
  cp -a "$JSON_BACKUP" "$PCS_JSON"
  chmod 0644 "$REGISTRY" "$PCS_JSON" 2>/dev/null || true
  chown root:www-data "$PCS_JSON" 2>/dev/null || true
  rm -f "$REG_BACKUP" "$JSON_BACKUP"
  nginx -t >/dev/null 2>&1 || true
  exit 1
}
trap 'rm -f "$TMP_CONF" "$REG_BACKUP" "$JSON_BACKUP"' EXIT

sed -e "s|__PC_NAME__|${NAME}|g" \
    -e "s|__BASE_DOMAIN__|${BASE_DOMAIN}|g" \
    -e "s|__REMOTE_PORT__|${PORT}|g" \
    "$TEMPLATE" > "$TMP_CONF"

install -m 0644 "$TMP_CONF" "$CONF"
printf '%s\t%s\t%s\t%s\n' "$NAME" "$PORT" "$LABEL" "$DESC" >> "$REGISTRY"

NAME="$NAME" LABEL="$LABEL" DESC="$DESC" python3 - "$PCS_JSON" <<'PY'
import json
import os
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
try:
    entries = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(entries, list):
        entries = []
except Exception:
    entries = []

entry = {
    "id": os.environ["NAME"],
    "name": os.environ["LABEL"] or os.environ["NAME"],
    "desc": os.environ["DESC"] or "DSH Web",
}
entries = [e for e in entries if isinstance(e, dict) and e.get("id") != entry["id"]]
entries.append(entry)
path.write_text(json.dumps(entries, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
PY
chown root:www-data "$PCS_JSON"
chmod 0644 "$PCS_JSON"

if ! nginx -t; then
  cleanup_failed
fi
systemctl reload nginx

echo
echo "added: https://${NAME}.${BASE_DOMAIN}/ -> 127.0.0.1:${PORT}"
echo "port:  ${PORT}"
echo "next on Windows:"
echo "  New-DshClient.ps1 -PcName ${NAME} -BaseDomain ${BASE_DOMAIN} -ServerIp <SERVER_IP> -FrpToken <TOKEN> -RemotePort ${PORT}"
echo "DNS: create ${NAME}.${BASE_DOMAIN} A <SERVER_IP> (or a wildcard A record)."
